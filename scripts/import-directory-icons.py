"""Import the selected, pinned Phosphor Regular SVGs for the Go directory page."""

from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
import urllib.request
import xml.etree.ElementTree as ET


COMMIT = "2b75f3ad12b420c9504ef05df8d2564a28f8500e"
BASE = f"https://raw.githubusercontent.com/phosphor-icons/core/{COMMIT}/"
ICONS = {
    "folder": "folder-simple",
    "package": "package",
    "archive": "file-archive",
    "metadata": "file-code",
    "signature": "file-lock",
    "checksum": "file-magnifying-glass",
    "disk": "disc",
    "link": "link-simple",
    "text": "file-text",
    "code": "file-code",
    "markdown": "file-md",
    "python": "file-py",
    "ini": "file-ini",
    "file": "file",
}
TAGS = {"svg", "g", "path", "rect", "circle", "ellipse", "line", "polyline", "polygon"}
ATTRIBUTES = {
    "viewBox", "width", "height", "fill", "fill-rule", "clip-rule", "d",
    "x", "y", "x1", "x2", "y1", "y2", "cx", "cy", "r", "rx", "ry",
    "points", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin",
    "stroke-miterlimit", "transform", "opacity",
}


def download(relative):
    request = urllib.request.Request(BASE + relative, headers={"User-Agent": "MirrorDock-icon-import"})
    with urllib.request.urlopen(request, timeout=30) as response:
        data = response.read(65537)
    if len(data) > 65536:
        raise ValueError(f"Unexpected asset size: {relative}")
    return data.decode("utf-8")


def svg_body(name):
    source = download(f"assets/regular/{name}.svg")
    if "<!" in source or "{{" in source:
        raise ValueError(f"Unexpected SVG declaration: {name}")
    root = ET.fromstring(source)
    if root.tag.rsplit("}", 1)[-1] != "svg" or root.get("viewBox") != "0 0 256 256":
        raise ValueError(f"Unexpected SVG root: {name}")
    for node in root.iter():
        node.tag = node.tag.rsplit("}", 1)[-1]
        if node.tag not in TAGS or set(node.attrib) - ATTRIBUTES:
            raise ValueError(f"Unsupported SVG markup: {name}")
        if (node.text or "").strip() or (node.tail or "").strip():
            raise ValueError(f"Unexpected SVG text: {name}")
        for attribute in ("fill", "stroke"):
            if node.get(attribute, "none") not in {"none", "currentColor"}:
                raise ValueError(f"Unsupported SVG paint: {name}")
        if any("url(" in value or "{{" in value for value in node.attrib.values()):
            raise ValueError(f"Unsupported SVG attribute: {name}")
    return "".join(ET.tostring(child, encoding="unicode") for child in root)


def main():
    license_text = download("LICENSE")
    if "-->" in license_text or "{{" in license_text:
        raise ValueError("Unexpected license markup")
    names = sorted(set(ICONS.values()))
    with ThreadPoolExecutor(max_workers=4) as executor:
        bodies = dict(zip(names, executor.map(svg_body, names), strict=True))
    lines = [
        "<!-- Generated by python3 scripts/import-directory-icons.py; do not edit.",
        f"Phosphor Icons Regular — https://github.com/phosphor-icons/core/tree/{COMMIT}",
        license_text.strip(),
        "-->",
        '{{define "icon"}}<svg class="phosphor-icon" viewBox="0 0 256 256" aria-hidden="true">',
    ]
    for index, (key, name) in enumerate(ICONS.items()):
        if key == "file":
            lines.append("{{else}}" + bodies[name])
        else:
            condition = "if" if index == 0 else "else if"
            lines.append('{{' + condition + ' eq . "' + key + '"}}' + bodies[name])
    lines.append("{{end}}</svg>{{end}}")
    destination = Path(__file__).resolve().parents[1] / "internal/mirrors/listing-icons.html"
    destination.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Imported {len(names)} official Regular SVGs ({len(ICONS)} type mappings).")


if __name__ == "__main__":
    main()
